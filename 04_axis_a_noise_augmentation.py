def compute_rms(signal: np.ndarray) -> float:
    """
    Compute Root Mean Square energy of a signal.

        RMS = √( (1/N) · Σ x[i]² )

    Args:
        signal: 1-D numpy array of audio samples.

    Returns:
        RMS energy as a float. Returns 0.0 for all-zero signals.
    """
    return float(np.sqrt(np.mean(signal ** 2)))


def mix_at_target_snr(
    clean: np.ndarray,
    noise: np.ndarray,
    target_snr_db: float,
) -> np.ndarray:
    """
    Mix a clean signal with noise at a precisely controlled SNR.

    Mathematical derivation (see module docstring §3):

        k = RMS_clean / (RMS_noise · 10^(SNR_target / 20))
        degraded = clean + k · noise

    After mixing, if any sample exceeds [-1, 1], the entire mixture is
    scaled down proportionally (preserves the SNR ratio while preventing
    digital clipping / wraparound distortion in 16-bit PCM).

    Args:
        clean:          1-D array, clean speech signal.
        noise:          1-D array, noise signal (same length as clean).
        target_snr_db:  Desired SNR in decibels.

    Returns:
        1-D array, the mixed (degraded) signal.
    """
    rms_clean = compute_rms(clean)
    rms_noise = compute_rms(noise)

    # Guard: if noise is silent, return clean unchanged
    if rms_noise < 1e-10:
        return clean.copy()

    # Guard: if clean is silent, return clean (nothing to degrade)
    if rms_clean < 1e-10:
        return clean.copy()

    # Calculate the required RMS for the noise to achieve target SNR
    #   target_snr = 20 * log10(rms_clean / rms_noise_desired)
    #   rms_noise_desired = rms_clean / 10^(target_snr / 20)
    target_rms_noise = rms_clean / (10.0 ** (target_snr_db / 20.0))

    # Scale factor: how much to multiply the raw noise by
    scale_factor = target_rms_noise / rms_noise

    # Scale noise and create mixture
    noise_scaled = noise * scale_factor
    mixed = clean + noise_scaled

    # Prevent clipping: scale down if any sample exceeds [-1, 1]
    # This preserves the SNR ratio exactly (both components scale equally)
    peak = np.max(np.abs(mixed))
    if peak > 1.0:
        mixed = mixed / peak

    return mixed


