def augment_all_utterances(manifest: pd.DataFrame, noise_source: NoiseSource) -> list:
    """
    Apply all noise types at all SNR levels to every utterance.

    Per proposal §9 (build order), processes noise types sequentially:
    White → Pink → Café, with all SNR levels within each type.

    Total output: 150 utterances × 3 noise types × 4 SNR levels = 1,800 files.

    Args:
        manifest:     DataFrame with 'utterance_id', 'wav_path' columns.
        noise_source: Initialized NoiseSource instance.

    Returns:
        List of dicts for the Axis A manifest.
    """
    records = []
    total = len(manifest) * len(NOISE_TYPES) * len(SNR_LEVELS)
    skipped = 0

    # Process in order: White → Pink → Café (proposal §9)
    with tqdm(total=total, desc="  Augmenting", unit="files") as pbar:
        for noise_type in NOISE_TYPES:
            for snr_db in SNR_LEVELS:
                for _, row in manifest.iterrows():
                    uid = row["utterance_id"]
                    clean_wav = row["wav_path"]
                    ground_truth = row.get("ground_truth_normalized",
                                          row.get("ground_truth_raw", ""))

                    # Output filename: {uid}_{noise_type}_{snr}db.wav
                    out_name = f"{uid}_{noise_type}_{snr_db}db.wav"
                    out_path = AXIS_A_DIR / out_name

                    # Idempotent: skip if file already exists
                    if out_path.exists():
                        records.append({
                            "utterance_id": uid,
                            "speaker_id": row["speaker_id"],
                            "noise_type": noise_type,
                            "snr_db": snr_db,
                            "degraded_wav_path": str(out_path),
                            "clean_wav_path": clean_wav,
                            "ground_truth_normalized": ground_truth,
                            "duration_s": row["duration_s"],
                        })
                        skipped += 1
                        pbar.update(1)
                        continue

                    # Load clean audio
                    clean_audio, _ = sf.read(clean_wav, dtype="float32")
                    n_samples = len(clean_audio)

                    # Generate noise of matching length
                    noise = noise_source.get_noise(noise_type, n_samples)

                    # Mix at target SNR using explicit RMS-based math
                    degraded = mix_at_target_snr(clean_audio, noise, snr_db)

                    # Save as 16-bit PCM WAV (same format as clean files)
                    sf.write(str(out_path), degraded, TARGET_SR, subtype="PCM_16")

                    records.append({
                        "utterance_id": uid,
                        "speaker_id": row["speaker_id"],
                        "noise_type": noise_type,
                        "snr_db": snr_db,
                        "degraded_wav_path": str(out_path),
                        "clean_wav_path": clean_wav,
                        "ground_truth_normalized": ground_truth,
                        "duration_s": row["duration_s"],
                    })
                    pbar.update(1)

    if skipped > 0:
        print(f"  [SKIP] {skipped} files already existed (idempotent)")

    return records


