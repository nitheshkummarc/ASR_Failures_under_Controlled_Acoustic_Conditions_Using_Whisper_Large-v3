def main():
    print("=" * 70)
    print("  04_axis_a_noise_augmentation.py")
    print("  Axis A: Additive Noise (White / Pink / Café) at 4 SNR levels")
    print("=" * 70)

    # --- Load manifest ---
    manifest_path = METADATA_DIR / "utterance_manifest.csv"
    if not manifest_path.exists():
        print(f"\n  [ERROR] Manifest not found: {manifest_path}")
        print("  Run 01_download_librispeech.py and 02_normalize_text.py first.")
        sys.exit(1)

    df = pd.read_csv(manifest_path)

    if "ground_truth_normalized" not in df.columns:
        print("\n  [ERROR] 'ground_truth_normalized' column missing.")
        print("  Run 02_normalize_text.py first.")
        sys.exit(1)

    print(f"\n  [LOAD] {len(df)} clean utterances from {manifest_path.name}")
    print(f"  [PLAN] {len(NOISE_TYPES)} noise types × {len(SNR_LEVELS)} SNRs "
          f"× {len(df)} utterances = {len(NOISE_TYPES) * len(SNR_LEVELS) * len(df)} "
          f"degraded files")

    # --- Initialize noise source ---
    clean_paths = df["wav_path"].tolist()
    noise_source = NoiseSource(clean_paths, sr=TARGET_SR, seed=RANDOM_SEED)

    # --- Run augmentation ---
    print(f"\n  [RUN]  Generating degraded audio files...\n")
    records = augment_all_utterances(df, noise_source)

    # --- Save Axis A manifest ---
    axis_a_df = pd.DataFrame(records)
    axis_a_manifest_path = METADATA_DIR / "axis_a_manifest.csv"
    axis_a_df.to_csv(axis_a_manifest_path, index=False)
    print(f"\n  [SAVED] {axis_a_manifest_path} ({len(axis_a_df)} rows)")

    # --- Validation ---
    print(f"\n{'=' * 70}")
    print("  VALIDATION CHECKS")
    print(f"{'=' * 70}")

    expected_total = len(df) * len(NOISE_TYPES) * len(SNR_LEVELS)
    assert len(axis_a_df) == expected_total, (
        f"Expected {expected_total} rows, got {len(axis_a_df)}"
    )

    # Verify all degraded files exist and have correct format
    sample_check = axis_a_df.sample(min(20, len(axis_a_df)), random_state=RANDOM_SEED)
    for _, row in sample_check.iterrows():
        info = sf.info(row["degraded_wav_path"])
        assert info.samplerate == TARGET_SR, \
            f"Wrong sample rate: {row['degraded_wav_path']}"
        assert info.channels == 1, \
            f"Not mono: {row['degraded_wav_path']}"

    # Print summary per noise type × SNR
    print(f"\n  ✓ {len(axis_a_df)} degraded WAV files generated/verified")
    print(f"  ✓ Format: 16 kHz, mono, 16-bit PCM")
    print(f"\n  Breakdown:")
    summary = axis_a_df.groupby(["noise_type", "snr_db"]).size().reset_index(name="count")
    for _, row in summary.iterrows():
        print(f"    {row['noise_type']:>5s}  {row['snr_db']:>2d} dB  →  "
              f"{row['count']} files")

    # Verify SNR accuracy on a few samples
    print(f"\n  SNR Verification (spot-check on 3 random samples):")
    verify_samples = axis_a_df.sample(3, random_state=RANDOM_SEED + 99)
    for _, row in verify_samples.iterrows():
        clean, _ = sf.read(row["clean_wav_path"], dtype="float32")
        degraded, _ = sf.read(row["degraded_wav_path"], dtype="float32")
        # Estimate actual SNR: noise ≈ degraded - clean
        estimated_noise = degraded - clean
        rms_s = compute_rms(clean)
        rms_n = compute_rms(estimated_noise)
        if rms_n > 1e-10:
            actual_snr = 20 * np.log10(rms_s / rms_n)
        else:
            actual_snr = float("inf")
        print(f"    {row['utterance_id']} | {row['noise_type']} | "
              f"target={row['snr_db']}dB | measured≈{actual_snr:.1f}dB")

    print(f"\n  Ready for Step 05 (Axis A inference & evaluation).\n")


if __name__ == "__main__":
    main()
