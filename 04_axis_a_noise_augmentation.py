"""
04_axis_a_noise_augmentation.py — Axis A: Additive Noise Augmentation
=====================================================================
This script applies controlled additive noise to the 150 clean LibriSpeech
utterances and saves 1,800 degraded WAV files (150 × 3 noise types × 4 SNRs).

Noise types:  White, Pink, Café (multi-talker babble)
SNR levels:   20 dB, 15 dB, 10 dB, 5 dB

Per proposal §3 (Axis A), §9 (build order), and the user's strict rule:
    The SNR mixing logic is written explicitly using numpy/librosa RMS math
    (NOT audiomentations) so the DSP is transparent and syllabus-aligned.


DSP PRIMER — Signal-to-Noise Ratio & RMS Energy
=================================================
(Links to "Speech Signal Characteristics" syllabus topic)

1. ROOT MEAN SQUARE (RMS) ENERGY
   ──────────────────────────────
   RMS measures the effective amplitude (average power) of a discrete signal:

       RMS(x) = √( (1/N) · Σᵢ x[i]² )

   For speech, RMS correlates with perceived loudness. Silent frames have
   near-zero RMS; voiced frames have high RMS.

2. SIGNAL-TO-NOISE RATIO (SNR) IN DECIBELS
   ────────────────────────────────────────
   SNR quantifies how far the desired signal stands above background noise:

       SNR_dB = 20 · log₁₀( RMS_signal / RMS_noise )

   The factor of 20 (not 10) is used because RMS is an amplitude quantity,
   and power ∝ amplitude². Key reference points:

       20 dB  →  noise barely perceptible
       15 dB  →  mild background noise
       10 dB  →  noise clearly audible, speech still intelligible
        5 dB  →  challenging listening; ASR degrades significantly
        0 dB  →  equal signal and noise power

3. SCALING NOISE TO ACHIEVE A TARGET SNR
   ──────────────────────────────────────
   Given clean signal s[n] and raw noise w[n], we want a scaling factor k
   such that the mixture s[n] + k·w[n] has exactly the target SNR:

       SNR_target = 20 · log₁₀( RMS_s / (k · RMS_w) )

   Solving for k:

       10^(SNR_target / 20) = RMS_s / (k · RMS_w)

       k = RMS_s / ( RMS_w · 10^(SNR_target / 20) )

   The degraded signal is then:

       degraded[n] = s[n] + k · w[n]

   If the mixture exceeds [-1, 1], we scale it down to prevent clipping
   while preserving the SNR ratio (both signal and noise are scaled equally).

4. NOISE TYPES
   ────────────
   WHITE NOISE:  Flat power spectral density across all frequencies.
                 Each sample drawn i.i.d. from 𝒩(0, 1).
                 All frequencies carry equal energy.

   PINK NOISE:   Power spectral density ∝ 1/f. Low frequencies carry more
                 energy than high frequencies. Perceived as a deeper, more
                 natural sound. Generated by filtering white noise with a
                 1/√f amplitude response in the frequency domain.

   CAFÉ BABBLE:  Multi-talker background simulating restaurant/café environments.
                 Generated by overlaying N speakers with random time offsets,
                 normalized to similar RMS, then summed. Individual words become
                 unintelligible in the mixture — only the "texture" of speech
                 remains, creating realistic babble noise.
                 (Source: MUSAN if available, else synthetic from clean utterances)
"""

