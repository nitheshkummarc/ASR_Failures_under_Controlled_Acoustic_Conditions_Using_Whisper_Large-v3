def generate_white_noise(n_samples: int, rng: np.random.Generator) -> np.ndarray:
    """
    Generate white noise with flat power spectral density.

    Each sample is drawn independently from 𝒩(0, 1).
    All frequencies carry equal energy per unit bandwidth.

    Args:
        n_samples: Number of samples to generate.
        rng:       numpy random Generator for reproducibility.

    Returns:
        1-D array of white noise samples.
    """
    return rng.standard_normal(n_samples)


def generate_pink_noise(n_samples: int, rng: np.random.Generator) -> np.ndarray:
    """
    Generate pink noise (1/f spectrum) via FFT filtering.

    Method:
      1. Generate white noise in the time domain.
      2. Compute its FFT (frequency domain representation).
      3. Multiply by a 1/√f amplitude filter:
         - White noise has flat PSD → power at each frequency is equal
         - Dividing amplitude by √f gives PSD ∝ 1/f (pink spectrum)
      4. Inverse FFT back to time domain.
      5. Normalize to unit standard deviation.

    The resulting signal has more energy at low frequencies, which is
    characteristic of many natural environmental sounds.

    Args:
        n_samples: Number of samples to generate.
        rng:       numpy random Generator for reproducibility.

    Returns:
        1-D array of pink noise samples.
    """
    # Step 1: white noise in time domain
    white = rng.standard_normal(n_samples)

    # Step 2: FFT (real-valued signal → rfft for efficiency)
    white_fft = np.fft.rfft(white)

    # Step 3: Build 1/√f amplitude filter
    freqs = np.fft.rfftfreq(n_samples, d=1.0 / TARGET_SR)
    # Avoid division by zero at DC (f=0)
    freqs[0] = 1.0
    pink_filter = 1.0 / np.sqrt(freqs)
    # Remove DC component entirely (no 0 Hz energy)
    pink_filter[0] = 0.0

    # Step 4: Apply filter and inverse FFT
    pink_fft = white_fft * pink_filter
    pink = np.fft.irfft(pink_fft, n=n_samples)

    # Step 5: Normalize to unit standard deviation
    std = np.std(pink)
    if std > 1e-10:
        pink = pink / std

    return pink


def write_noise_source(path, signal: np.ndarray, sr: int) -> None:
    """
    Write a noise SOURCE buffer to disk without clipping it.

    The generators normalize to unit standard deviation, which for a roughly
    Gaussian signal puts about a third of the samples outside [-1, 1]. Handing
    that straight to soundfile as PCM_16 hard-clips every one of them: the
    previously stored cafe.wav had 30% of its samples pinned to the rails and a
    crest factor of 1.42, where natural babble sits around 3-5. The stored
    "babble" was therefore a squared-off, distorted version of what was
    generated, and because clipping is phase-dependent it also broke the
    spectral match between the babble and its phase-randomized SSN control.

    Peak-normalizing first avoids all of it. The absolute level written here is
    irrelevant downstream — every consumer re-normalizes on load, and
    mix_at_target_snr rescales the noise to hit the requested SNR — so only the
    waveform SHAPE needs to survive the round trip.
    """
    peak = float(np.max(np.abs(signal)))
    if peak > 0:
        signal = signal / peak * 0.95

    path.parent.mkdir(parents=True, exist_ok=True)
    sf.write(str(path), signal, sr, subtype="PCM_16")


def generate_speech_shaped_noise(
    source: np.ndarray,
    rng: np.random.Generator,
) -> np.ndarray:
    """
    Build speech-shaped noise (SSN) by randomizing the phase of `source`.

    This is the experimental control that separates the two masking mechanisms.
    A babble masker differs from white noise in two ways at once: its energy sits
    in the speech bands, and it carries linguistic content. Comparing cafe
    against white cannot attribute the damage to either cause on its own.

    Phase randomization changes exactly one of them. Taking the rFFT, replacing
    every phase with a uniform draw on [0, 2*pi) and inverting leaves the
    magnitude spectrum — and therefore the long-term average spectrum and the
    total power — unchanged, while destroying the temporal envelope and any
    intelligible content.

        ssn  - white  ->  energetic masking from spectral overlap
        cafe - ssn    ->  informational masking (what energy cannot explain)

    DC and, for even-length input, Nyquist must stay real: they have no conjugate
    partner, so an imaginary part there would be silently discarded by irfft.

    Args:
        source: 1-D array whose spectrum should be matched (the cafe babble).
        rng:    numpy random Generator for reproducibility.

    Returns:
        1-D array, same length as `source`, normalized to unit standard
        deviation.
    """
    n = len(source)
    spectrum = np.fft.rfft(source)
    magnitude = np.abs(spectrum)

    random_phase = rng.uniform(0.0, 2.0 * np.pi, size=magnitude.shape)
    random_phase[0] = 0.0                      # DC stays real
    if n % 2 == 0:
        random_phase[-1] = 0.0                 # Nyquist stays real

    ssn = np.fft.irfft(magnitude * np.exp(1j * random_phase), n=n)

    std = np.std(ssn)
    if std > 1e-10:
        ssn = ssn / std

    return ssn


def generate_cafe_babble(
    clean_wav_paths: list,
    duration_s: float,
    sr: int,
    n_speakers: int = 15,
    rng: np.random.Generator = None,
) -> np.ndarray:
    """
    Generate synthetic multi-talker babble (café noise) from clean utterances.

    This is a standard technique in speech processing research (cf. NOISEX-92
    babble noise). By overlaying many speakers at random time offsets, individual
    words become unintelligible — only the "texture" of speech remains.

    Method:
      1. Select n_speakers random utterances from the clean set.
      2. Create a buffer of target duration.
      3. For each utterance:
         a. Load audio, normalize to unit RMS.
         b. Place at a random offset within the buffer.
         c. If the utterance is shorter than the buffer, it occupies
            only its portion; the rest stays zero.
      4. Sum all speakers and normalize the final babble.

    Args:
        clean_wav_paths: List of paths to clean WAV files.
        duration_s:      Target duration of the babble signal (seconds).
        sr:              Sample rate.
        n_speakers:      Number of speakers to overlay.
        rng:             numpy random Generator for reproducibility.

    Returns:
        1-D array of synthetic café babble noise.
    """
    if rng is None:
        rng = np.random.default_rng(RANDOM_SEED)

    target_samples = int(duration_s * sr)
    babble = np.zeros(target_samples, dtype=np.float64)

    # Select random utterances (with replacement if needed)
    n_available = len(clean_wav_paths)
    indices = rng.choice(n_available, size=min(n_speakers, n_available), replace=False)

    logger.info(f"  [BABBLE] Generating {duration_s}s café babble from "
          f"{len(indices)} speakers...")

    for idx in indices:
        wav_path = clean_wav_paths[idx]
        audio, _ = sf.read(wav_path, dtype="float32")

        # Normalize this speaker to unit RMS
        rms = compute_rms(audio)
        if rms > 1e-10:
            audio = audio / rms

        # Tile the audio to ensure it covers the entire target buffer
        repeats = (target_samples // len(audio)) + 2
        tiled_audio = np.tile(audio, repeats)

        # Apply a random starting offset so the speakers are out of phase
        offset = rng.integers(0, len(audio))
        speaker_track = tiled_audio[offset: offset + target_samples]

        # Add to the mix
        babble += speaker_track

    # Normalize final babble to unit standard deviation
    std = np.std(babble)
    if std > 1e-10:
        babble = babble / std

    logger.info(f"  [BABBLE] Done — {target_samples} samples, "
          f"RMS={compute_rms(babble):.4f}")
    return babble


