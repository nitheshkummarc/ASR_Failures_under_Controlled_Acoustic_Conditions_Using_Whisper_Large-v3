class NoiseSource:
    """
    Manages noise generation for all three Axis A noise types.

    White and Pink noise are generated fresh for each utterance (matching
    the utterance length). Café babble is pre-generated as a long source
    signal, and segments are extracted per utterance.
    """

    def __init__(self, clean_wav_paths: list, sr: int, seed: int = RANDOM_SEED):
        self.sr = sr
        self.clean_wav_paths = clean_wav_paths

        # Separate RNG streams per noise type. This is a reproducibility
        # requirement, not a style choice: with one shared generator, the number
        # of draws taken by one noise type would shift every subsequent value
        # produced for the others.
        self._rng_white = np.random.default_rng(seed)
        self._rng_pink = np.random.default_rng(seed + 1)
        self._cafe_seed = seed + 2
        self._rng_cafe = np.random.default_rng(self._cafe_seed)

        # Café noise: lazy initialization
        self._cafe_source = None
        self._cafe_offset = 0

    def _ensure_cafe_loaded(self):
        """
        Load or generate the café noise source on first use.

        This is the ONLY place café babble is produced. scripts/02_run_axis_a.py
        used to contain a second generator that built the babble from the 150
        TEST utterances, which would have contaminated the experiment: an
        utterance could end up masked by babble containing itself. That
        duplicate has been removed — all café noise now comes through here, from
        a strictly disjoint speaker pool.
        """
        if self._cafe_source is not None:
            return

        # Option 1: load a cached or externally supplied (e.g. MUSAN) file.
        if CAFE_NOISE_PATH.exists():
            logger.info(f"  [CAFE] Loading cafe noise from: {CAFE_NOISE_PATH}")
            audio, _ = sf.read(str(CAFE_NOISE_PATH), dtype="float32")
            std = np.std(audio)
            if std > 1e-10:
                audio = audio / std
            self._cafe_source = audio
            logger.info(f"  [CAFE] Loaded {len(self._cafe_source)} samples "
                        f"({len(self._cafe_source) / self.sr:.1f}s)")
            return

        # Option 2: synthesise babble from utterances DISJOINT from the test set.
        logger.info(f"  [CAFE] No cafe noise file at {CAFE_NOISE_PATH}")
        logger.info("  [CAFE] Generating synthetic disjoint babble from unused utterances...")
        logger.info("         (To use real cafe noise, place a WAV file at the path above)")
        logger.info("         (Download from MUSAN: https://www.openslr.org/17/)")

        if not LIBRISPEECH_ROOT.exists():
            raise FileNotFoundError(
                f"Raw LibriSpeech directory not found: {LIBRISPEECH_ROOT}. "
                "Run scripts/00_prepare_corpus.py first."
            )

        all_flacs = sorted(LIBRISPEECH_ROOT.rglob("*.flac"))

        # Exclude the 150 test utterances so no speaker masks itself.
        test_ids = {Path(p).stem for p in self.clean_wav_paths}
        disjoint_paths = [str(p) for p in all_flacs if p.stem not in test_ids]

        if not disjoint_paths:
            raise RuntimeError(
                "No utterances left after excluding the test set — cannot build "
                "disjoint cafe babble."
            )

        logger.info(f"  [CAFE] Found {len(disjoint_paths)} disjoint utterances for babble synthesis.")

        self._cafe_source = generate_cafe_babble(
            disjoint_paths,
            duration_s=CAFE_BABBLE_DURATION_S,
            sr=self.sr,
            n_speakers=CAFE_BABBLE_N_SPEAKERS,
            rng=self._rng_cafe,
        )

        # Cache so subsequent runs load instead of regenerating (and so the
        # exact noise used is auditable on disk).
        CAFE_NOISE_PATH.parent.mkdir(parents=True, exist_ok=True)
        sf.write(str(CAFE_NOISE_PATH), self._cafe_source, self.sr, subtype="PCM_16")
        logger.info(f"  [CAFE] Cached babble to {CAFE_NOISE_PATH}")

        # Record which speakers went into the babble, so the disjointness claim
        # in the report is verifiable rather than merely asserted.
        provenance = {
            "n_speakers_requested": CAFE_BABBLE_N_SPEAKERS,
            "duration_s": CAFE_BABBLE_DURATION_S,
            "sample_rate": self.sr,
            "seed": self._cafe_seed,
            "disjoint_pool_size": len(disjoint_paths),
            "excluded_test_utterances": sorted(test_ids),
        }
        provenance_path = CAFE_NOISE_PATH.with_suffix(".provenance.json")
        provenance_path.write_text(json.dumps(provenance, indent=2), encoding="utf-8")
        logger.info(f"  [CAFE] Wrote provenance to {provenance_path}")

    def get_noise(self, noise_type: str, n_samples: int) -> np.ndarray:
        """
        Get a noise segment of the specified type and length.

        Args:
            noise_type: One of "white", "pink", "cafe".
            n_samples:  Number of samples needed (matches utterance length).

        Returns:
            1-D noise array of length n_samples.
        """
        if noise_type == "white":
            return generate_white_noise(n_samples, self._rng_white)

        elif noise_type == "pink":
            return generate_pink_noise(n_samples, self._rng_pink)

        elif noise_type == "cafe":
            self._ensure_cafe_loaded()
            return self._extract_cafe_segment(n_samples)

        else:
            raise ValueError(f"Unknown noise type: {noise_type}")

    def _extract_cafe_segment(self, n_samples: int) -> np.ndarray:
        """
        Extract a segment of café noise of the specified length.

        Uses a sliding offset to ensure different utterances get different
        segments. If the source runs out, it wraps around.
        """
        source_len = len(self._cafe_source)

        if n_samples >= source_len:
            # Utterance longer than source: tile the source
            repeats = (n_samples // source_len) + 1
            tiled = np.tile(self._cafe_source, repeats)
            return tiled[:n_samples]

        # Extract segment at current offset
        if self._cafe_offset + n_samples > source_len:
            # Wrap around
            self._cafe_offset = 0

        segment = self._cafe_source[self._cafe_offset: self._cafe_offset + n_samples]
        self._cafe_offset += n_samples

        return segment.copy()


